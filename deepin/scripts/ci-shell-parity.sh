#!/bin/sh
# ci-shell-parity.sh — 批 DV / DW · 「判据层的结论不许随执行 shell 变」的门（覆盖面版）
#
# 【为什么要有它 —— 承接批 DT / 批 DU】
#   批 DT 立了承诺（「判据结果的诊断输出不许随执行 shell 变」）⇒ 批 DU 给它装上牙齿
#   （`ci.sh` 第 9 步双跑**接线门**）⇒ 但**只覆盖了一个脚本** ⇒
#   ⚠⚠⚨ 别的判据脚本（`ci-d2.sh` / `ci-orphan-probe.sh` …）**结论照样可能随 shell 变**
#   ⇒ 而**没有任何一道门**会发现 ⇒ 本脚本把覆盖面扩出去。
#
# 【机制】
#   读**仓内常驻登记册** `ci-shell-parity.baseline` ⇒ 逐条对「标 DUAL 且双跑位置是本脚本」的条目
#   ⇒ `sh` 跑一遍 + `bash` 跑一遍 ⇒ **退出码必须一致** + **输出必须逐字节一致**
#   ⇒ 任一不同 ⇒ 判红（批 DU 同款口径：假红比假绿更坏 ⇒ 差异落文件再读，不用 `| head`）。
#
# ⚠⚠⚨ **为什么登记册里要有「豁免」条目（EXEMPT）**：
#   「哪些判据脚本被双跑」这条承诺，**若只记被双跑的那些** ⇒ 覆盖面可以被**悄悄改窄**
#   （新增一个判据脚本 ⇒ 不双跑 ⇒ 没人知道）⇒ 批 DQ 立过的教训
#   （「一条本该被登记的承诺，在三个目录上从未生效」）⇒
#   ⇒ **CI 里跑的每一个 shell 判据脚本都必须在登记册里** ⇒ 要么 DUAL，要么 EXEMPT + 理由
#   ⇒ 且 EXEMPT 的理由必须**真实**（不是「懒得跑」）。
#
# ⚠⚠⚨ **「入口共用 ≠ 口径共用」**（批 DG 教训）：
#   `ci.sh` 第 9 步也双跑接线门（批 DU）⇒ 那**不是**本脚本的口径 ⇒
#   ⇒ 登记册里用「**双跑位置**」这一列区分（`ci.sh` / `parity`）⇒ 两边各算各的。
#
# ⚠⚠⚨ **「入口共用 ≠ 参数共用」**（批 DW）：
#   `ci-d2.sh` 吃的是**源码根**，而 `ci-platform-probe.sh` 吃的是**已构建的二进制**
#   ⇒ ⇒ 登记册里用「**参数**」这一列显式写出来（`src` / `bin`）
#   ⇒ 靠脚本名**猜**参数 ⇒ 就是把约定藏起来 ⇒ 换个参数 ⇒ 没人发现。
#
# 用法：scripts/ci-shell-parity.sh [源码根目录]（默认脚本所在目录的上一级）
#   ⚠ 批 DW：**环境里必须有 `BIN`**（指向已构建的二进制）⇒ 它由 `ci.sh` export
#     ⇒ 单一真相源（两个地方各算一遍 ⇒ 算出不同路径 ⇒ 又一个新洞）
#     ⇒ 没有它 ⇒ 登记册里标 `bin` 的条目**双跑不了** ⇒ 拒绝继续（fail closed）
set -uo pipefail

SRC="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
# ⚠⚠⚨ 归一化成**绝对路径**（批 DV 实测）：相对路径传给子判据脚本 ⇒ 子脚本按**自己**
#   的口径去解析那个路径 ⇒ 两遍**一起红**（孤儿探针会把整棵树判成「游离」）
#   ⇒ 「两版一致」变成**空洞的一致** ⇒ 假绿 ⇒ 绝对路径 ⇒ 两遍跑的才是真判据
SRC_ABS="$(cd "$SRC" 2>/dev/null && pwd)"
# ⚠ 仓库根（`macos/` 与 `deepin/` 同仓）⇒ 登记册的键用**相对仓库根的路径**（批 CY 教训）
ROOT="$(cd "$SRC/.." && pwd)"
BASE="$SRC/scripts/ci-shell-parity.baseline"
# ⚠ 批 DW：二进制路径**只从环境拿**（`ci.sh` export）⇒ 单一真相源
BIN="${BIN:-}"

TAB=$(printf '\t')

# ⚠⚠⚨ 批 EA · **递归保护**（负控 NC26 实测撞上）：本脚本**自己**的登记册键
#   ⇒ ⇒ 登记册里自己那行若是 `parity` 位置 ⇒ 本脚本会**自己跑自己** ⇒ ⇒ **无限递归**
#   ⇒ ⇒ 实测：进程链一路往下 ⇒ **CI 挂死**（比假绿更坏：什么都得不到）
#   ⇒ ⇒ **认出自己** ⇒ 自己那行若是 `parity` ⇒ **拒绝继续**（fail closed ⇒ 变红）
#   ⚠ **两种键都认**：登记册的键是**相对仓库根**的路径（批 CY 纪律）
#   ⇒ `$SRC` 是 `deepin/` 时键是 `deepin/scripts/ci-shell-parity.sh`
#   ⇒ `$SRC` 是仓库根时键是 `scripts/ci-shell-parity.sh`
_SELF_REL="$SRC/scripts/ci-shell-parity.sh"
_SELF_KEY_ROOT="scripts/ci-shell-parity.sh"

if [ ! -f "$BASE" ]; then
    echo "✗ 双跑登记册不存在：$BASE ⇒ 「哪些判据脚本被双跑」这件事**无处可查** ⇒ 拒绝继续" >&2
    exit 1
fi

# ⚠⚠⚨ 差异落文件（不落 `$BUILD` ⇒ 免得第二遍比第一遍多看到第一遍的产物 ⇒ 自己制造分叉）
_SA="${TMPDIR:-/tmp}/deepdolphin-parity-sh.$$.log"
_SB="${TMPDIR:-/tmp}/deepdolphin-parity-bash.$$.log"
_SD="${TMPDIR:-/tmp}/deepdolphin-parity-diff.$$.log"

n_dual=0
# ⚠⚠⚨ 批 DZ：**由 CI 入口双跑**的那几条也要计数
#   ⇒ 否则汇总行只说「本脚本双跑了几个」⇒ 登记册的三个数字对不上
#   ⇒ 谁被漏掉**看不出来**（批 DQ 教训：一条本该被登记的承诺，从未生效）
n_dual_cish=0
n_exempt=0
n_ok=0

# ⚠⚠⚨ 批 ED · **双跑覆盖面门不许把自己的结论建立在外部门的可达性上**
#   ⇒ ⚠⚠⚨ **实测坐实的洞**：被双跑的 `contract-check.sh` 第 21 组要打**真 GitHub API**
#     ⇒ 那一组**打得到** ⇒ 整门退出码 **0**；**打不到** ⇒ 退出码 **3**
#     ⇒ ⇒ **同一份代码**，两遍的退出码就在 **0/3 之间摆**
#     ⇒ ⇒ 外部网络在两遍之间一翻转 ⇒ 双跑门**自造分叉** ⇒ ⇒ CI **间歇性假红**
#     ⇒ ⇒ 而且**误诊**：把「外部依赖变了」归因成「结论随执行 shell 变」
#       ⇒ 读者被带去查错的地方（批 CE 纪律：诊断失真最贵）
#   ⇒ ⇒ **修法 = 把外部依赖钉死**（⚠ **不是**把结论归一化 —— 批 DV/DY 纪律：
#     **产出侧清随机量**，不做比较侧归一化 ⇒ 真实差异照样被双跑门抓到）
#     ⇒ 两遍的**输入**必须一致 ⇒ 否则「两版一致」这句话本身**没有意义**
#   ⇒ 钉成「**打不通**」⇒ 依赖网络的那一条**恒定** ⇒ 恒定退出码 ⇒ 两遍不可能分叉
#   ⚠⚠⚨ **两处用途分离**（不许混为一谈）：
#     · **本脚本**（登记册的 `parity` 位置）= 覆盖面探针 ⇒ 只问「随 shell 变吗」
#       ⇒ 外部依赖**钉死** ⇒ 这一处「打不到」是**故意**的
#     · **`ci.sh` 第 10 步** = **真跑**契约门 ⇒ **必须真打真 API**
#       ⇒ 那里的网络**不许钉** ⇒ 两处结论**各自负责**
#   ⚠⚠⚨ **只钉「出网」，不许钉「本机」**：`no_proxy` 必须**显式收窄到本机**
#     ⇒ 契约门第 21 组会起一个**本地打桩服务器**（本机某个随机端口）
#     ⇒ 代理**不许**把它一起吞掉 ⇒ 否则「重试」那几条会变成「打桩服务器没起来」
#     ⇒ ⇒ 覆盖面被**悄悄改窄**（批 DQ 教训：一条本该被登记的承诺从未生效）
#   ⚠ **大小写两种都设**（值相同）⇒ 环境里**已有**的大写变量被压住
#     ⇒ 不会有工具挑到另一个值 ⇒ 钉死才真的生效
export _PIN_PROXY="http://127.0.0.1:9"
export http_proxy="$_PIN_PROXY"
export https_proxy="$_PIN_PROXY"
export all_proxy="$_PIN_PROXY"
export HTTP_PROXY="$_PIN_PROXY"
export HTTPS_PROXY="$_PIN_PROXY"
export ALL_PROXY="$_PIN_PROXY"
export no_proxy="127.0.0.1,localhost,::1"
# ⚠⚠⚨ 批 EJ-18 · **显式契约**：本轮**不许打外网**（外部依赖不许进入结论）
#   ⇒ ⚠⚠⚨ 实测坐实：上面那组代理**钉死是软的** ⇒ ⇒ curl 还读 `~/.curlrc`
#     ⇒ ⇒ 里面的 `noproxy = "*"` **绕过代理** ⇒ ⇒ 真 API 那条照样打得到
#     ⇒ ⇒ 契约门 rc 在 0/3 之间摆 ⇒ ⇒ 双跑门**自造分叉** ⇒ ⇒ CI **间歇性假红**
#   ⇒ ⇒ 现在由**契约门自己**认这个开关 ⇒ ⇒ 恒定不打 ⇒ ⇒ 恒定输出 + 恒定退出码
#   ⇒ ⚠ **代理那组钉死仍然保留**（纵深防御：万一以后有第二个出网点）
#   ⇒ ⚠ **只影响本脚本的子进程** ⇒ ⇒ `ci.sh` 第 10 步**真跑**仍真打真 API
export DEEPGIT_CONTRACT_OFFLINE=1
# ⚠ 批 EJ-18：**把这一轮的性质报出来**（不许「结论悄悄消失」⇒ 读者得知道这轮是离线的）
echo "› 本轮钉死出网：外部依赖不进入结论（覆盖面探针 ⇒ 只问「结论随执行 shell 变吗」）"
export NO_PROXY="127.0.0.1,localhost,::1"
while IFS="$TAB" read -r rel mode where param why; do
    [ -z "$rel" ] && continue
    case "$rel" in '#'*) continue ;; esac
    if [ "$mode" = "EXEMPT" ]; then
        # ⚠⚠⚨ 豁免**必须**写理由（否则「不双跑」就成了一句空话 ⇒ 覆盖面被悄悄改窄）
        if [ -z "$why" ]; then
            echo "✗ 双跑登记册里 $rel 标了 EXEMPT 却**没写理由** ⇒ 「为什么不双跑」没人负责 ⇒ 拒绝继续" >&2
            exit 1
        fi
        n_exempt=$((n_exempt + 1))
        continue
    fi
    if [ "$mode" != "DUAL" ]; then
        echo "✗ 双跑登记册里有不认识的状态：$rel ⇒ $mode（只许 DUAL 或 EXEMPT）" >&2
        exit 1
    fi
    if [ -z "$why" ]; then
        echo "✗ 双跑登记册里 $rel 标了 DUAL 却**没写理由**（为什么它能双跑）⇒ 拒绝继续" >&2
        exit 1
    fi
    # ⚠⚠⚨ 批 DW：段数必须**恰好 5** ⇒ 理由里混进 TAB ⇒ 多出来的那段会被吞进理由
    #   ⇒ 机器看不出「登记册被人动过」⇒ ⇒ 段数错位 ⇒ 拒绝继续
    _why_rest="${why#*"$TAB"}"
    if [ "$_why_rest" != "$why" ]; then
        echo "✗ 双跑登记册里 $rel 的理由里**混进了 TAB** ⇒ 段数不是 5 ⇒ 登记册被人动过 ⇒ 拒绝继续" >&2
        exit 1
    fi
    if [ "$where" != "parity" ] && [ "$where" != "ci.sh" ]; then
        echo "✗ 双跑登记册里有不认识的双跑位置：$rel ⇒ $where（只许 parity 或 ci.sh）" >&2
        exit 1
    fi
    # ⚠⚠⚨ 批 EA · **递归保护**（fail closed）：登记册里**本脚本自己**那行
    #   ⇒ ⇒ 若是 `parity` 位置 ⇒ 本脚本会**自己跑自己** ⇒ ⇒ **无限递归**
    #   ⇒ ⇒ 实测：进程链一路往下 ⇒ **CI 挂死**（比假绿更坏：什么都得不到）
    #   ⇒ ⇒ **拒绝继续** ⇒ ⇒ 变成**红的**而不是挂死的
    #   ⚠ 两种键都认（登记册的键 = 相对仓库根 ⇒ `$SRC` 可能是仓库根也可能是 `deepin/`）
    case "$rel" in
        "$_SELF_REL"|"$_SELF_KEY_ROOT"|*/ci-shell-parity.sh)
            if [ "$where" = "parity" ]; then
                echo "✗ 双跑登记册里**双跑覆盖面门自己**（$rel）被列在 \`parity\` 位置" >&2
                echo "  ⇒ 本脚本会**自己跑自己** ⇒ **无限递归** ⇒ CI 会挂死 ⇒ 拒绝继续" >&2
                exit 1
            fi
            ;;
    esac
    if [ "$where" != "parity" ]; then
        # 位置是 `ci.sh` ⇒ 由批 DU 的门项负责（那半边在 CI 入口里）⇒ 本脚本不管
        # ⚠⚠⚨ 批 DZ：但**要计数** ⇒ parity / ci.sh / 豁免 三个数字必须对得上
        n_dual_cish=$((n_dual_cish + 1))
        continue
    fi
    # ⚠⚠⚨ 批 DW：参数列只许 `src` 或 `bin` ⇒ 别的 ⇒ 「传给它的参数是谁」没人知道
    #   ⇒ 双跑的**输入都不确定** ⇒ 拒绝继续
    if [ "$param" != "src" ] && [ "$param" != "bin" ]; then
        echo "✗ 双跑登记册里有不认识的参数：$rel ⇒ $param（只许 src 或 bin）⇒ 「双跑时喂给它什么」没人知道 ⇒ 拒绝继续" >&2
        exit 1
    fi
    # ⚠⚠⚨ 批 DW：`bin` 的前置检查 ⇒ 二进制不在 ⇒ 子脚本会走「用法错」那条路（exit 2）
    #   ⇒ **两遍都那样** ⇒ 「两版一致」又变成**空洞的一致** ⇒ 假绿 ⇒ ⇒ 必须先挡住
    if [ "$param" = "bin" ]; then
        # ⚠⚠⚨ 批 DW：**`-f` 也要查**（实测踩出来的）：`-x` 对**目录**也返回 true
        #   ⇒ 目录能通过「可执行」检查 ⇒ 喂给探针的是**目录** ⇒ 探针要等到 exec 时才炸
        #   ⇒ 而两个 shell 的**报错文案不同**（dash 说 Permission denied / bash 说 是一个目录）
        #   ⇒ 双跑门会报「输出不同」⇒ **误诊**（真正的问题是「二进制不是文件」）
        #   ⇒ ⇒ 必须在**喂之前**就挡住（fail closed）⇒ 这一组**根本没验过**，不许当成通过
        if [ -z "$BIN" ] || [ ! -f "$BIN" ] || [ ! -x "$BIN" ]; then
            echo "✗ 双跑登记册里的 $rel 要双跑**二进制**（参数列 = bin）⇒ 但 BIN=${BIN:-（没设）} 不是一个可执行的二进制**文件** ⇒ 双跑做不了 ⇒ 这一组**根本没验过**（不许当成通过）" >&2
            exit 1
        fi
        _arg="$BIN"
    else
        _arg="$SRC_ABS"
    fi
    n_dual=$((n_dual + 1))
    _script="$ROOT/$rel"
    if [ ! -r "$_script" ]; then
        echo "✗ 双跑登记册里的脚本读不了：$_script ⇒ 双跑做不了 ⇒ 这一组**根本没验过**（不许当成通过）" >&2
        exit 1
    fi
    _rc_a=0
    sh   "$_script" "$_arg" > "$_SA" 2>&1 || _rc_a=$?
    _rc_b=0
    bash "$_script" "$_arg" > "$_SB" 2>&1 || _rc_b=$?
    if [ "$_rc_a" -ne "$_rc_b" ]; then
        echo "✗ ⚠⚠⚨ $rel 在 sh 与 bash 下**退出码不同**（sh=$_rc_a / bash=$_rc_b）⇒ ⚠ **先查外部依赖**（网络/时间/环境）在两遍之间**有没有变**（⚠⚠⚨ **批 ED** 实测坐实：契约门第 21 组要打真 GitHub API ⇒ 整门退出码随网络可达性在 **0/3** 之间摆 ⇒ ⇒ 两遍之间网络一翻转 ⇒ 双跑门**自造分叉** ⇒ ⇒ 归因成「随执行 shell 变」是**误诊**）⇒ 外部依赖钉死后仍不同 ⇒ 才是真的「结论随执行 shell 变」⇒ 不可信（批 DT）" >&2
        exit 1
    fi
    if ! cmp -s "$_SA" "$_SB"; then
        # ⚠⚠⚨ 批 DX：**两遍都没跑通** ⇒ **不是**「随执行 shell 变」⇒ 诊断不许指错方向
        #   （批 CE 纪律：诊断失真比假红更坏 ⇒ 读者会被带去查错的地方）
        #   ⇒ 到这里两遍的**退出码已经相等**（不等的那一支在上面就 exit 了）⇒ ⇒ 只看退出码即可
        #   ⇒ 退出码非 0 ⇒ 真因多半在「**喂的参数**」/「**环境坏没坏**」⇒ 先查那两个
        #   ⇒ 退出码 0（两遍都跑通）⇒ 才是真的「**诊断文案随 shell 变**」
        if [ "$_rc_a" -ne 0 ]; then
            echo "✗ ⚠⚠⚨ $rel 在 sh 与 bash 下**输出不同**，但**两遍都没跑通**（退出码 sh=$_rc_a / bash=$_rc_b）⇒ ⚠ 这**不是**「随执行 shell 变」⇒ 先查「喂的参数对不对」「环境坏没坏」（批 DX）" >&2
        else
            echo "✗ ⚠⚠⚨ $rel 在 sh 与 bash 下**输出不同**（退出码 sh=$_rc_a / bash=$_rc_b）⇒ 诊断文案**随执行 shell 变** ⇒ 负控的文案命中判定不可信（批 DT）" >&2
        fi
        _drc=0
        diff "$_SA" "$_SB" > "$_SD" 2>&1 || _drc=$?
        echo "   差异已写 $_SD（diff 退出码 $_drc）前 20 行：" >&2
        head -20 "$_SD" >&2
        exit 1
    fi
    n_ok=$((n_ok + 1))
    # ⚠⚠⚨ 批 DW：把**子判据的退出码**报出来 ⇒ 「一致」这两个字**不掩盖**它到底跑通没跑通
    #   ⇒ 门打绿勾，读者还能看到「这一组其实没跑通」⇒ 结论不许悄悄消失
    _rc_note="判据**真的跑通**"
    if [ "$_rc_a" -ne 0 ]; then
        _rc_note="这一组**没跑通**；结论本身由该脚本自己的门负责"
    fi
    echo "  ✓ $rel：两版一致（退出码 $_rc_a ⇒ $_rc_note）"
done < "$BASE"

echo "✓ 双跑覆盖面：登记册共 $((n_dual + n_dual_cish + n_exempt)) 条 = 本脚本双跑 $n_dual 个（sh 与 bash 下**输出与退出码一致**）+ CI 入口双跑 $n_dual_cish 个 + 豁免 $n_exempt 个（每个带理由）"
