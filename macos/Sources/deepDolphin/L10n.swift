// L10n.swift — 多语言本地化系统（zh-CN / en / zh-TW / ja）
//
// 设计：
// - 语言切换存 UserDefaults，启动时恢复；不依赖系统语言
// - 字符串表用 [String: String] 字典（编译期不查漏，但 miss 时回退 en→zh-CN→key）
// - 视图中用 `L10n.t("key")` 或 `L10n.shared.str.keyName` 访问
// - 固定长文（About/Help/OpenSource/Changelog）走 `L10n.shared.doc(.about)` 等
import Foundation
import Combine

enum AppLanguage: String, CaseIterable, Identifiable {
    case zhCN = "zh-CN"
    case en    = "en"
    case zhTW  = "zh-TW"
    case ja    = "ja"
    /// 事实层文本（KPI 标题/范围标签/状态词等纯层字符串）目前只有 zh/en 两套；
    /// 繁中与简中共用中文事实，日文回落英文事实。界面上新增的键不走这里（四语言全有）。
    var usesEnglishFacts: Bool { self == .en || self == .ja }

    var id: String { rawValue }
    var label: String {
        switch self {
        case .zhCN: return "简体中文"
        case .en:   return "English"
        case .zhTW: return "繁體中文"
        case .ja:   return "日本語"
        }
    }
}

